import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { REGULATION_MC_ROSTER, REGULATION_MC_SOURCE } from '../src/data/regulationMc.js'

// Pin artwork independently of competitive data; regenerate deliberately.
const SPRITES_COMMIT = '97a7832d307311c0e1c6ea9035308bf80cc94f81'
const root = new URL('../', import.meta.url)
const directory = new URL('public/images/pokemon/', root)
const indexPath = new URL('scripts/data/pokeapi-image-index.json', root)
await mkdir(directory, { recursive: true })
if (process.argv.includes('--refresh-index')) {
  const response = await fetch('https://pokeapi.co/api/v2/pokemon?limit=100000', { signal: AbortSignal.timeout(30000) })
  if (!response.ok) throw new Error(`Image index: HTTP ${response.status}`)
  const { results } = await response.json()
  const ids = Object.fromEntries(results.map(({ name, url }) => [name, Number(url.match(/\/(\d+)\/$/)[1])]))
  await mkdir(new URL('scripts/data/', root), { recursive: true })
  await writeFile(indexPath, `${JSON.stringify(ids, null, 2)}\n`)
}
const index = JSON.parse(await readFile(indexPath, 'utf8'))
const images = {}, missing = []
let cursor = 0, completed = 0, totalBytes = 0
await Promise.all(Array.from({ length: 6 }, async () => {
  while (cursor < REGULATION_MC_ROSTER.length) {
    const pokemon = REGULATION_MC_ROSTER[cursor++]
    const id = index[pokemon.apiName]
    if (!id) throw new Error(`No exact image identity for ${pokemon.displayName}; refresh the image index.`)
    const candidates = [`other/home/${id}.png`, `other/official-artwork/${id}.png`, `${id}.png`]
    let found = false
    for (const path of candidates) {
      const source = `https://raw.githubusercontent.com/PokeAPI/sprites/${SPRITES_COMMIT}/sprites/pokemon/${path}`
      const response = await fetch(source, { signal: AbortSignal.timeout(30000) })
      if (response.status === 404) continue
      if (!response.ok) throw new Error(`${pokemon.showdownId}: HTTP ${response.status}`)
      const filename = `${pokemon.showdownId}.webp`
      const { size } = await sharp(Buffer.from(await response.arrayBuffer()))
        .resize({ width: 256, height: 256, fit: 'inside', withoutEnlargement: true })
        .webp({ quality: 82, effort: 5 }).toFile(fileURLToPath(new URL(filename, directory)))
      totalBytes += size
      images[pokemon.showdownId] = { file: filename, resourceId: id, source: path }
      found = true
      break
    }
    if (!found) missing.push(pokemon.showdownId)
    if (++completed % 50 === 0) console.log(`${completed}/${REGULATION_MC_ROSTER.length} images checked`)
  }
}))
const ordered = Object.fromEntries(Object.entries(images).sort(([a], [b]) => a.localeCompare(b)))
await writeFile(new URL('src/data/pokemonImages.js', root),
  `// Generated by npm run assets:pokemon. Exact forms only.\n` +
  `export const POKEMON_IMAGE_SOURCE = ${JSON.stringify({ repository: 'PokeAPI/sprites', commit: SPRITES_COMMIT, rosterCommit: REGULATION_MC_SOURCE.commit })}\n` +
  `export const POKEMON_IMAGES = ${JSON.stringify(ordered, null, 2)}\n` +
  `export const MISSING_POKEMON_IMAGES = ${JSON.stringify(missing.sort())}\n`)
console.log(JSON.stringify({ images: Object.keys(images).length, missing, totalBytes }))
